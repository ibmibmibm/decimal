#include <boost/decimal.hpp>
#include <boost/core/lightweight_test.hpp>

using namespace boost::decimal;
using namespace boost::decimal::literals;

// The expected values are tgamma(x) and lgamma(x) rounded once, from mpmath
void test_nearest()
{
    BOOST_TEST_EQ(lgamma(-0.4931421_DF), 1.265972_DF);
    BOOST_TEST_EQ(lgamma(2.000035_DF), 0.00001479785_DF);
    BOOST_TEST_EQ(lgamma(0.6904320377435727_DD), 0.2726710571828580_DD);
    BOOST_TEST_EQ(lgamma(-1.571600551999013_DD), 0.8339730971913114_DD);
    BOOST_TEST_EQ(tgamma(0.1065147393968503_DD), 8.907281974045078_DD);
    BOOST_TEST_EQ(tgamma(2.777888607785128_DD), 1.645792718800306_DD);
    BOOST_TEST_EQ(lgamma("1.999992313508627251330398517594896"_DL), "-0.000003249709092191545788178585633722518"_DL);
    BOOST_TEST_EQ(lgamma("1.999267716855652254158601528698225"_DL), "-0.0003094248965614802469466193086039391"_DL);
    BOOST_TEST_EQ(tgamma("5.738606924673095332535777848563221"_DL), "77.30966170911779751629240914951190"_DL);
    BOOST_TEST_EQ(tgamma("-9.347214083146897626561460454863833"_DL), "0.000004438074276741396212853225180254121"_DL);
    BOOST_TEST_EQ(lgamma(2.000035_DFF), 0.00001479785_DFF);
    BOOST_TEST_EQ(tgamma(2.777888607785128_DDF), 1.645792718800306_DDF);
    BOOST_TEST_EQ(tgamma("-9.347214083146897626561460454863833"_DLF), "0.000004438074276741396212853225180254121"_DLF);

    // Next to the roots of lgamma near -2.457 and -2.748
    BOOST_TEST_EQ(lgamma("-2.457024738220800623039454147651179"_DL), "8.233312608824862437428400226427401E-34"_DL);
    BOOST_TEST_EQ(lgamma("-2.457024738220800623039454147651180"_DL), "-6.922721871391710778942179820684618E-34"_DL);
    BOOST_TEST_EQ(lgamma("-2.747682646727412601391488482691499"_DL), "-1.332122858536063067972129717966750E-33"_DL);
    BOOST_TEST_EQ(lgamma("-2.747682646727412601391488482691500"_DL), "5.822273270755357485226018566429270E-34"_DL);
    BOOST_TEST_EQ(lgamma(-2.457025_DL), "-3.967531242633807811849799036948574E-7"_DL);

    // Exact values, integers, small, negative and large arguments
    BOOST_TEST_EQ(tgamma(5_DD), 24_DD);
    BOOST_TEST_EQ(tgamma(35_DL), "2.9523279903960414084761860964352E+38"_DL);
    BOOST_TEST_EQ(lgamma(1_DD), 0_DD);
    BOOST_TEST_EQ(lgamma(2_DF), 0_DF);
    BOOST_TEST_EQ(tgamma(0.5_DD), 1.772453850905516_DD);
    BOOST_TEST_EQ(tgamma(-0.5_DD), -3.544907701811032_DD);
    BOOST_TEST_EQ(tgamma(1E-10_DD), 9999999999.422784_DD);
    BOOST_TEST_EQ(lgamma(1E-300_DD), 690.7755278982137_DD);
    BOOST_TEST_EQ(lgamma(1E+20_DD), 4.505170185988091E+21_DD);
    BOOST_TEST_EQ(lgamma("-100000000000000000000.5"_DL), "-4505170185988091368081.808819875965"_DL);
    BOOST_TEST_EQ(tgamma(2.048E-95_DF), 4.882812E+94_DF);
    BOOST_TEST_EQ(tgamma(-2.048E-95_DF), -4.882813E+94_DF);
    BOOST_TEST_EQ(tgamma(1.6777216E-61_DD), 5.960464477539062E+60_DD);
    BOOST_TEST_EQ(tgamma("1.125899906842624E-76"_DL), "8.881784197001252323389053344726562E+75"_DL);
    BOOST_TEST(isinf(tgamma(300_DD)));
    BOOST_TEST(isnan(tgamma(-3_DD)));
}

void test_directed()
{
    #ifndef BOOST_DECIMAL_NO_CONSTEVAL_DETECTION
    // fesetround has an effect only with the detection of constant evaluation
    fesetround(rounding_mode::fe_dec_downward);
    BOOST_TEST_EQ(lgamma(73.88057_DF), 242.7557_DF);
    BOOST_TEST_EQ(tgamma(40.54722_DF), 1.530804E+47_DF);
    BOOST_TEST_EQ(lgamma(-5.334430249110662_DD), -4.081421301812420_DD);
    BOOST_TEST_EQ(lgamma(0.1420878675093712_DD), 1.884849152833185_DD);
    BOOST_TEST_EQ(tgamma(1E-95_DF), 9.999999E+94_DF);
    BOOST_TEST_EQ(tgamma(1E-61_DD), 9.999999999999999E+60_DD);
    BOOST_TEST_EQ(tgamma("1.024E-76"_DL), "9.765624999999999999999999999999999E+75"_DL);
    BOOST_TEST_EQ(lgamma("-2.457024738220800623039454147651180"_DL), "-6.922721871391710778942179820684619E-34"_DL);

    fesetround(rounding_mode::fe_dec_upward);
    BOOST_TEST_EQ(tgamma(0.3631528_DF), 2.450483_DF);
    BOOST_TEST_EQ(tgamma(15.86723730468348_DD), 909296514659.9900_DD);
    BOOST_TEST_EQ(tgamma(-3.791849285048550_DD), 0.2929898885051774_DD);
    BOOST_TEST_EQ(lgamma("-0.7509075114865893430360491026231036"_DL), "1.578338873770376595189774401397785"_DL);
    BOOST_TEST_EQ(tgamma("0.9957008022874010082146867631625347"_DL), "1.002499917535442049931508427623701"_DL);
    BOOST_TEST_EQ(tgamma(36_DL), "1.03331479663861449296666513375232E+40"_DL);
    BOOST_TEST_EQ(tgamma(37_DLF), "3.719933267899012174679994481508352E+41"_DLF);
    BOOST_TEST_EQ(tgamma(37_DD), 3.719933267899013E+41_DD);
    BOOST_TEST_EQ(lgamma("-2.747682646727412601391488482691499"_DL), "-1.332122858536063067972129717966749E-33"_DL);

    fesetround(rounding_mode::fe_dec_toward_zero);
    BOOST_TEST_EQ(lgamma(-0.9892593_DF), 4.538408_DF);
    BOOST_TEST_EQ(tgamma(13.61888_DF), 2.321706E+9_DF);
    BOOST_TEST_EQ(lgamma(-2.7476826_DL), "-8.945261007966772515305676455110887E-8"_DL);

    fesetround(rounding_mode::fe_dec_to_nearest);
    #endif
}

int main()
{
    test_nearest();
    test_directed();

    return boost::report_errors();
}
