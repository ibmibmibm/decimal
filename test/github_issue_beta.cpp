#include <boost/decimal.hpp>
#include <boost/core/lightweight_test.hpp>

using namespace boost::decimal;
using namespace boost::decimal::literals;

// The expected values are beta(x, y) rounded once, from MPFR
void test_nearest()
{
    BOOST_TEST_EQ(beta(0.6433012_DF, 7.624039_DF), 0.3840460_DF);
    BOOST_TEST_EQ(beta(2.5E-8_DF, 3.3_DF), 4.000000E+7_DF);
    BOOST_TEST_EQ(beta(450.5_DF, 12.25_DF), 1.967509E-25_DF);
    BOOST_TEST_EQ(beta(15000000_DF, 2.5_DF), 1.525485E-18_DF);
    BOOST_TEST_EQ(beta(0.00001_DF, 0.00002_DF), 150000.0_DF);
    BOOST_TEST_EQ(beta(8.478146222086584_DD, 6.532202020135201_DD), 4.564224164790154E-5_DD);
    BOOST_TEST_EQ(beta(1E-12_DD, 3.5_DD), 999999999998.3196_DD);
    BOOST_TEST_EQ(beta(123456789.5_DD, 2.25_DD), 7.052163769527766E-19_DD);
    BOOST_TEST_EQ(beta(31.67_DD, 4.229_DD), 2.950169839459318E-6_DD);
    BOOST_TEST_EQ(beta(94.71_DD, 74.57_DD), 1.421542252383689E-51_DD);
    BOOST_TEST_EQ(beta(2.5_DL, 3.5_DL), "0.03681553890925538951323410214780667"_DL);
    BOOST_TEST_EQ(beta(0.5_DL, 0.75_DL), "2.396280469471184414879844984560648"_DL);
    BOOST_TEST_EQ(beta(1E+12_DL, 0.5_DL), "1.772453850905737584029530686691853E-6"_DL);
    BOOST_TEST_EQ(beta(2.5_DF, 3E+20_DF), 8.527723E-52_DF);
    BOOST_TEST_EQ(beta(7.25_DD, 1.5E+40_DD), 6.110314983364985E-289_DD);
    BOOST_TEST_EQ(beta(1E+16_DL, 0.5_DL), "1.772453850905516049453840619660096E-8"_DL);
    BOOST_TEST_EQ(beta(450.5_DFF, 12.25_DFF), 1.967509E-25_DFF);
    BOOST_TEST_EQ(beta(8.478146222086584_DDF, 6.532202020135201_DDF), 4.564224164790154E-5_DDF);
    BOOST_TEST_EQ(beta(2.5_DLF, 3.5_DLF), "0.03681553890925538951323410214780667"_DLF);

    // Next to a rounding boundary, where the first try in one word cannot round
    BOOST_TEST_EQ(beta(0.01521764939251307_DD, 0.6102113647190278_DD), 66.63219503300242_DD);
    BOOST_TEST_EQ(beta(2.756084486793622_DD, 1.445022860470693_DD), 0.1843065838311140_DD);
    BOOST_TEST_EQ(beta(3.835580771716829_DD, 3.805342215629882_DD), 0.009388569052835387_DD);
    BOOST_TEST_EQ(beta(73.05_DD, 7.276_DD), 2.471105538548987E-11_DD);
    BOOST_TEST_EQ(beta(73.54_DD, 77.4_DD), 1.568735042630946E-46_DD);

    // Next to a rounding boundary, where the first try in two words cannot round
    BOOST_TEST_EQ(beta(1.5839_DL, 0.3_DL), "2.789655106765619945656214390710858"_DL);

    // Exact values: beta(x, 1) = 1 / x, and beta(n, z) for an integer n
    BOOST_TEST_EQ(beta(4_DF, 1_DF), 0.25_DF);
    BOOST_TEST_EQ(beta(1_DD, 0.5_DD), 2_DD);
    BOOST_TEST_EQ(beta(4_DF, 2_DF), 0.05_DF);
    BOOST_TEST_EQ(beta(0.25_DD, 2_DD), 3.2_DD);
    BOOST_TEST_EQ(beta(2_DL, 4_DL), 0.05_DL);
    BOOST_TEST_EQ(beta(0.5_DL, 0.5_DL), "3.141592653589793238462643383279503"_DL);

    // Integers that do not give an exact value, and results beyond the range
    BOOST_TEST_EQ(beta(3_DF, 0.5_DF), 1.066667_DF);
    BOOST_TEST_EQ(beta(35_DL, "1.234567890123456789012345678901234"_DL), "0.01124260013365521402163827083529929"_DL);
    BOOST_TEST_EQ(beta(2_DL, 1E-80_DL), 1E+80_DL);
    BOOST_TEST_EQ(beta(500_DF, 500_DF), 0_DF);
    BOOST_TEST_EQ(beta(1E+20_DD, 1E+20_DD), 0_DD);
    BOOST_TEST_EQ(beta(1E+14_DD, 3E+14_DD), 0_DD);
    BOOST_TEST_EQ(beta(500_DF, 1E+15_DF), 0_DF);
    BOOST_TEST_EQ(beta(std::numeric_limits<decimal64_t>::infinity(), 2_DD), 0_DD);
    BOOST_TEST(isinf(beta(1E-99_DF, 2E-99_DF)));

    // An argument that is not positive is a domain error
    BOOST_TEST(isnan(beta(-0.5_DF, 2_DF)));
    BOOST_TEST(isnan(beta(2_DD, 0_DD)));
    BOOST_TEST(isnan(beta(-0_DL, 0.5_DL)));
    BOOST_TEST(isnan(beta(-1.5_DL, 0.25_DL)));

    // A tiny x: 1 / x = 4.8828125E+49 is a tie, and beta is above it for y < 1 and below it for y > 1
    BOOST_TEST_EQ(beta(2.048E-50_DF, 0.5_DF), 4.882813E+49_DF);
    BOOST_TEST_EQ(beta(2.048E-50_DF, 2_DF), 4.882812E+49_DF);
    BOOST_TEST_EQ(beta(1E-30_DL, 2.5_DL), "9.999999999999999999999999999987196E+29"_DL);
    BOOST_TEST_EQ(beta(3E-50_DF, 2_DF), 3.333333E+49_DF);
    BOOST_TEST_EQ(beta(4_DL, 1E-19_DL), "9.999999999999999998166666666666667E+18"_DL);

    // An integer n with z = a * 10^-k: 10^k past 128 bits, the largest k for the exact test, and the first k past it
    BOOST_TEST_EQ(beta(2_DL, "1.234567890123456789012345678901234E-25"_DL), "8.100000072900000663390005036849059E+24"_DL);
    BOOST_TEST_EQ(beta(35_DL, "0.01234567890123456789012345678901234"_DL), "76.99415163699814323539027066774191"_DL);
    BOOST_TEST_EQ(beta(3_DL, "0.001234567890123456789012345678901234"_DL), "808.5021649296529462927019039617891"_DL);
}

void test_directed()
{
    #ifndef BOOST_DECIMAL_NO_CONSTEVAL_DETECTION
    // fesetround has an effect only with the detection of constant evaluation
    fesetround(rounding_mode::fe_dec_upward);
    BOOST_TEST_EQ(beta(15000000_DF, 2.5_DF), 1.525486E-18_DF);
    BOOST_TEST_EQ(beta(8.478146222086584_DD, 6.532202020135201_DD), 4.564224164790155E-5_DD);
    BOOST_TEST_EQ(beta(73.05_DD, 7.276_DD), 2.471105538548988E-11_DD);
    BOOST_TEST_EQ(beta(2.5_DL, 3.5_DL), "0.03681553890925538951323410214780668"_DL);
    BOOST_TEST_EQ(beta(4_DF, 2_DF), 0.05_DF);
    BOOST_TEST_EQ(beta(0.25_DD, 2_DD), 3.2_DD);
    BOOST_TEST_EQ(beta(2_DL, 4_DL), 0.05_DL);
    BOOST_TEST_EQ(beta(2.048E-50_DF, 2_DF), 4.882813E+49_DF);
    BOOST_TEST_EQ(beta(2_DD, 1E+15_DD), 9.999999999999991E-31_DD);
    BOOST_TEST_EQ(beta(0.001_DD, 1E+30_DD), 932.7165339900022_DD);
    BOOST_TEST_EQ(beta(1E+20_DD, 1E+20_DD), 1E-398_DD);
    BOOST_TEST_EQ(beta(1E+14_DD, 3E+14_DD), 1E-398_DD);
    BOOST_TEST_EQ(beta(35_DL, "0.01234567890123456789012345678901234"_DL), "76.99415163699814323539027066774192"_DL);

    fesetround(rounding_mode::fe_dec_downward);
    BOOST_TEST_EQ(beta(2.5E-8_DF, 3.3_DF), 3.999999E+7_DF);
    BOOST_TEST_EQ(beta(0.00001_DF, 0.00002_DF), 149999.9_DF);
    BOOST_TEST_EQ(beta(0.5_DL, 0.75_DL), "2.396280469471184414879844984560647"_DL);
    BOOST_TEST_EQ(beta(3_DL, 1234567890123456789_DL), "1.062882028697814516879524359889010E-54"_DL);
    BOOST_TEST_EQ(beta(4_DF, 2_DF), 0.05_DF);
    BOOST_TEST_EQ(beta(2_DL, 1E-80_DL), "9.999999999999999999999999999999999E+79"_DL);
    BOOST_TEST_EQ(beta(2.048E-50_DF, 0.5_DF), 4.882812E+49_DF);
    BOOST_TEST_EQ(beta(2_DL, "1.234567890123456789012345678901234E-25"_DL), "8.100000072900000663390005036849058E+24"_DL);
    BOOST_TEST_EQ(beta(3_DL, "0.001234567890123456789012345678901234"_DL), "808.5021649296529462927019039617890"_DL);

    fesetround(rounding_mode::fe_dec_to_nearest);
    #endif
}

int main()
{
    test_nearest();
    test_directed();

    return boost::report_errors();
}
