// The expected values are atan(x) and atan2(y, x) rounded once, from Python's decimal module
void test_nearest()
{
    // Arguments made to put the result next to a rounding boundary, closer than the last stage told apart
    BOOST_TEST_EQ(atan("9300000000333066039276590483231480e-22"_DL), "1570796326793821350414155899760836e-33"_DL);
    BOOST_TEST_EQ(atan2(-706769671991716e15_DD, 84269082123139e0_DD), -1570796326794896e-15_DD);
    #if BOOST_DECIMAL_DEC_EVAL_METHOD == 0 // A wider evaluation type rounds twice
    BOOST_TEST_EQ(atan2(-719503001399017e-13_DD, -4571621877575879e0_DD), -3141592653589777e-15_DD);
    BOOST_TEST_EQ(atan2(158333388209131e-12_DD, -1442824916580675e0_DD), 3141592653589683e-15_DD);
    #endif
    BOOST_TEST_EQ(atan2("1461952564260925182864745558008366e-5"_DL, "147386416731487001088246460114397e0"_DL), "9919181101536850980609545584540469e-38"_DL);
    BOOST_TEST_EQ(atan2("730585404241281072675969636705671e1"_DL, "5315420607196357315075069771074872e0"_DL), "9418145512817586345400107069522942e-34"_DL);
    BOOST_TEST_EQ(atan(0.05_DF), 0.04995840_DF);
    BOOST_TEST_EQ(atan(0.05_DD), 0.04995839572194276_DD);
    BOOST_TEST_EQ(atan(0.05_DL), "0.04995839572194276141000628703484488"_DL);
    BOOST_TEST_EQ(atan(0.01_DL), "0.009999666686665238206340116209279549"_DL);
    BOOST_TEST_EQ(atan(1E-40_DL), 1E-40_DL);
    BOOST_TEST_EQ(atan("-0.5892067299081487533440595915372664"_DL), "-0.5324454702390584674534036153852551"_DL);
    // Where two words leave the result to three, and one word to two
    BOOST_TEST_EQ(atan(1.07_DL), "0.8192017070909034209463922188695074"_DL);
    BOOST_TEST_EQ(atan2(1_DL, 11_DL), "0.09065988720074511349838667530846562"_DL);
    BOOST_TEST_EQ(atan(2_DD), 1.107148717794091_DD);
    BOOST_TEST_EQ(atan2(2_DD, 1_DD), 1.107148717794091_DD);
    BOOST_TEST_EQ(atan2(5.084777E-8_DF, -1.221514E-12_DF), 1.570820_DF);
    BOOST_TEST_EQ(atan2(-9.889701E-11_DF, -5.737004E-12_DF), -1.628741_DF);
    BOOST_TEST_EQ(atan2(-1234.564356728940_DD, -1189779.630989923_DD), -3.140555012768344_DD);
    BOOST_TEST_EQ(atan2(-6.862956853956393E-10_DD, -0.000005364629725944915_DD), -3.141464723850611_DD);
    BOOST_TEST_EQ(atan2("7.008931184813850285755811658047442E-8"_DL, "-0.04225572226405051731999031722715888"_DL), "3.141590994895820145416852322544857"_DL);
    BOOST_TEST_EQ(atan2("-835981859.6245254303217756935217128"_DL, "494960112168673.4338021395666511274"_DL), "-0.000001688988342840125745029701458576222"_DL);
    BOOST_TEST_EQ(atan(1E-60_DD), 1.000000000000000E-60_DD);
    BOOST_TEST_EQ(atan(-0.003_DF), -0.002999991_DF);
    BOOST_TEST_EQ(atan(0.5_DD), 0.4636476090008061_DD);
    BOOST_TEST_EQ(atan(-0.99_DL), "-0.7803730800666358988978715172725503"_DL);
    BOOST_TEST_EQ(atan(1_DF), 0.7853982_DF);
    BOOST_TEST_EQ(atan(1E+300_DD), 1.570796326794897_DD);
    BOOST_TEST_EQ(atan2(1_DD, 1E+40_DD), 1.000000000000000E-40_DD);
    BOOST_TEST_EQ(atan2(3_DD, 4E+12_DD), 7.500000000000000E-13_DD);
    BOOST_TEST_EQ(atan2(3_DF, 4E+12_DF), 7.500000E-13_DF);
    BOOST_TEST_EQ(atan2(1_DL, 1E+25_DL), 1E-25_DL);
    BOOST_TEST_EQ(atan2(0.002_DD, 3_DD), 0.0006666665679012609_DD);
    BOOST_TEST_EQ(atan2(1_DD, 1000_DD), 0.0009999996666668667_DD);
    BOOST_TEST_EQ(atan2(0.2_DD, 3_DD), 0.06656816377582380_DD);
    BOOST_TEST_EQ(atan2(1_DD, 10_DD), 0.09966865249116203_DD);
    BOOST_TEST_EQ(atan2(0.2_DL, 3_DL), "0.06656816377582380419864669429397107"_DL);
    BOOST_TEST_EQ(atan2(0.002_DL, 3_DL), "0.0006666665679012609053414331467925336"_DL);
    BOOST_TEST_EQ(atan2(1_DL, 1E+40_DL), 1E-40_DL);
    BOOST_TEST_EQ(atan2(1E-6170_DL, 1E+5_DL), 1E-6175_DL);
    BOOST_TEST_EQ(atan2(1_DL, 300_DL), "0.003333320987736624861198407405281840"_DL);
    BOOST_TEST_EQ(atan2(7_DD, 3_DD), 1.165904540509813_DD);
    BOOST_TEST_EQ(atan2(3_DD, 7_DD), 0.4048917862850834_DD);
    BOOST_TEST_EQ(atan2(-1_DF, -3_DF), -2.819842_DF);
    BOOST_TEST_EQ(atan2(2_DD, 2_DD), 0.7853981633974483_DD);
    BOOST_TEST_EQ(atan2(-1234.564356728940_DDF, -1189779.630989923_DDF), -3.140555012768344_DDF);
    BOOST_TEST_EQ(atan2(5.084777E-8_DFF, -1.221514E-12_DFF), 1.570820_DFF);
    BOOST_TEST_EQ(atan("-0.5892067299081487533440595915372664"_DLF), "-0.5324454702390584674534036153852551"_DLF);
    // A small exact quotient whose q^3/3 term ends on a rounding boundary: the next term decides past three words
    BOOST_TEST_EQ(atan("1.050000000000000000000000000025E-14"_DL), "1.049999999999999999999999999986412E-14"_DL);
    BOOST_TEST_EQ(atan2("2.10000000000000000000000000005E-14"_DL, 2_DL), "1.049999999999999999999999999986412E-14"_DL);
    // A small quotient next above a rounding boundary by about q^3/3: the result is next below the boundary
    #if BOOST_DECIMAL_DEC_EVAL_METHOD == 0 // A wider evaluation type rounds twice
    BOOST_TEST_EQ(atan2(3.114641_DF, 2007157_DF), 1.551767E-6_DF);
    BOOST_TEST_EQ(atan2(3.114641_DFF, 2007157_DFF), 1.551767E-6_DFF);
    BOOST_TEST_EQ(atan2(1.842525704921904_DD, 3728327474531769_DD), 4.941963165811506E-16_DD);
    BOOST_TEST_EQ(atan2(-7.055520471225018_DDF, 8690947026867031_DDF), -8.118241256578499E-16_DDF);
    #endif
    BOOST_TEST_EQ(atan2("15.91860512311962209483436005959732"_DL, "9629702852149667410167273374173647"_DL), "1.653073346865117877906510410668246E-33"_DL);
    // The same for a quotient in [1/64, 0.1), where one word is not sufficient for decimal32_t
    #if BOOST_DECIMAL_DEC_EVAL_METHOD == 0 // A wider evaluation type rounds twice
    BOOST_TEST_EQ(atan2(81687.27_DF, 3959103_DF), 0.02062985_DF);
    #endif
    // A result next to a rounding boundary that is a constant plus a small term, where the values of the argument next to
    // each other give results that three words do not tell apart
    BOOST_TEST_EQ(atan("-8135365505498883242719566342517174e-10"_DL), "-1570796326794896619231320462438679e-33"_DL);
    BOOST_TEST_EQ(atan2("1e0"_DL, "-1507732405790141530031244708951253e-59"_DL), "1570796326794896619231321706717076e-33"_DL);
    BOOST_TEST_EQ(atan2("-6618005355384197169399375105820975e-57"_DL, "-1e0"_DL), "-3141592653589793238462636765274147e-33"_DL);
}

void test_directed()
{
    #ifndef BOOST_DECIMAL_NO_CONSTEVAL_DETECTION
    // fesetround has an effect only with the detection of constant evaluation
    fesetround(rounding_mode::fe_dec_downward);
    // Arguments made to put the result next to a rounding boundary, closer than the last stage told apart
    BOOST_TEST_EQ(atan("9300000002273430093274342714546160e-22"_DL), "1570796326793821350414380245240481e-33"_DL);
    BOOST_TEST_EQ(atan2("644801186004406179555655321062259e4"_DL, "4407046099533916731364192111789144e0"_DL), "1570112853267093007966709407576076e-33"_DL);
    BOOST_TEST_EQ(atan2("-95383531403626537092686366236957e-13"_DL, "-187332006835914089957126267515000e0"_DL), "-3141592653589742321626265724713432e-33"_DL);
    BOOST_TEST_EQ(atan(-2.206814_DF), -1.145333_DF);
    BOOST_TEST_EQ(atan(-394952671107993.2_DD), -1.570796326794895_DD);
    BOOST_TEST_EQ(atan("-36664.68652901188993426419044905825"_DL), "-1.570769052594721451683076171619218"_DL);
    BOOST_TEST_EQ(atan2(9.258818E+11_DF, -3.596536E+11_DF), 1.941301_DF);
    BOOST_TEST_EQ(atan("-3.00000000000000000000000001E-16"_DL), "-3.000000000000000000000000009999910E-16"_DL);
    BOOST_TEST_EQ(atan2("-6.00000000000000000000000002E-16"_DL, 2_DL), "-3.000000000000000000000000009999910E-16"_DL);
    BOOST_TEST_EQ(atan2(929.7802769310495_DD, 85804.76753509128_DD), 0.01083557376775061_DD);
    BOOST_TEST_EQ(atan2("8194.175721799908004419907635340890"_DL, "-515.3449464535053570459986576380949"_DL), "1.633605218675387025744968097611059"_DL);
    BOOST_TEST_EQ(atan(1E-60_DD), 9.999999999999999E-61_DD);
    BOOST_TEST_EQ(atan2(1_DD, 1E+40_DD), 9.999999999999999E-41_DD);
    BOOST_TEST_EQ(atan2(3_DD, 4E+12_DD), 7.499999999999999E-13_DD);
    BOOST_TEST_EQ(atan2(3_DF, 4E+12_DF), 7.499999E-13_DF);
    BOOST_TEST_EQ(atan2(1_DL, 1E+25_DL), "9.999999999999999999999999999999999E-26"_DL);
    BOOST_TEST_EQ(atan2(1_DF, 3E+20_DF), 3.333333E-21_DF);
    BOOST_TEST_EQ(atan2(5_DL, -2E-30_DL), "1.570796326794896619231321691640151"_DL);
    BOOST_TEST_EQ(atan2(0_DF, -1_DF), 3.141592_DF);
    #ifndef BOOST_DECIMAL_FAST_MATH
    BOOST_TEST_EQ(atan(std::numeric_limits<decimal64_t>::infinity()), 1.570796326794896_DD);
    BOOST_TEST_EQ(atan2(-std::numeric_limits<decimal64_t>::infinity(), 1_DD), -1.570796326794897_DD);
    #endif

    fesetround(rounding_mode::fe_dec_upward);
    // Arguments made to put the result next to a rounding boundary, closer than the last stage told apart
    BOOST_TEST_EQ(atan("9300000001676573850569644003596187e-22"_DL), "1570796326793821350414311236540927e-33"_DL);
    BOOST_TEST_EQ(atan2(1305796339220605e11_DD, -681022511538168e0_DD), 1570796326800113e-15_DD);
    BOOST_TEST_EQ(atan2("-2251200432848196330721018080003250e-15"_DL, "-2790714322640765548836865908209431e0"_DL), "-3141592653589792431787300592206614e-33"_DL);
    BOOST_TEST_EQ(atan("-2263061744532635944315674759121888e-10"_DL), "-1570796326794896619231317272847367e-33"_DL);
    BOOST_TEST_EQ(atan2("1e0"_DL, "7384755608044209858469968755291049e-56"_DL), "1570796326794896619231247844083671e-33"_DL);
    BOOST_TEST_EQ(atan2("3791910884197169399375105820974945e-60"_DL, "-1e0"_DL), "3141592653589793238462643379487592e-33"_DL);
    BOOST_TEST_EQ(atan(7.5_DL), "1.438244794498222597961404247935482"_DL);
    BOOST_TEST_EQ(atan2(1_DF, 3E+20_DF), 3.333334E-21_DF);
    BOOST_TEST_EQ(atan2(1E-30_DD, -1_DD), 3.141592653589794_DD);
    BOOST_TEST_EQ(atan2(8.123441_DF, 2087649_DF), 3.891191E-6_DF);
    BOOST_TEST_EQ(atan2(4.186991691574218_DD, 5530285175051819_DD), 7.571023119137768E-16_DD);
    BOOST_TEST_EQ(atan2("6.856782119325288913281512944950362"_DL, "9883791024125240397451804476562953"_DL), "6.937400945233101711231770346147213E-34"_DL);
    BOOST_TEST_EQ(atan2(1_DF, 0_DF), 1.570797_DF);
    #ifndef BOOST_DECIMAL_FAST_MATH
    BOOST_TEST_EQ(atan2(std::numeric_limits<decimal32_t>::infinity(), -std::numeric_limits<decimal32_t>::infinity()), 2.356195_DF);
    BOOST_TEST_EQ(atan2(std::numeric_limits<decimal64_t>::infinity(), std::numeric_limits<decimal64_t>::infinity()), 0.7853981633974484_DD);
    BOOST_TEST_EQ(atan2(1_DD, -std::numeric_limits<decimal64_t>::infinity()), 3.141592653589794_DD);
    #endif

    fesetround(rounding_mode::fe_dec_toward_zero);
    BOOST_TEST_EQ(atan2(-2_DL, 3E+40_DL), "-6.666666666666666666666666666666666E-41"_DL);

    fesetround(rounding_mode::fe_dec_to_nearest_from_zero);


    fesetround(rounding_mode::fe_dec_to_nearest);
    #endif
}

// A signaling NaN operand gives a quiet NaN (IEEE 754 6.2)
template <typename T>
void test_snan()
{
    #ifndef BOOST_DECIMAL_FAST_MATH
    const T one {1};

    for (const auto s : {snan<T>("7"), -snan<T>("7")})
    {
        BOOST_TEST(is_quiet_of(atan(s), s));
        BOOST_TEST(is_quiet_of(atan2(s, one), s));
        BOOST_TEST(is_quiet_of(atan2(one, s), s));
    }
    #endif
}

int main()
{
    test_nearest();
    test_directed();
    test_snan<decimal32_t>();
    test_snan<decimal64_t>();
    test_snan<decimal128_t>();
    test_snan<decimal_fast32_t>();
    test_snan<decimal_fast64_t>();
    test_snan<decimal_fast128_t>();

    return boost::report_errors();
}
